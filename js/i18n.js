function normalizeText(text) {
  return text.replace(/[🌱🛒👨‍🌾👑📧🔒👤📱📍📊📦💬📈🚪➕❤️]/g, '').replace(/→/g, '').trim();
}

function translateText(original, lang) {
  if (lang === 'en') return original;
  const normalized = normalizeText(original);
  return translations[lang]?.[normalized] || original;
}

function applyLanguage(lang) {
  document.documentElement.lang = lang;

  const selector = 'h1, h1 span, h2, h3, h4, p, a, button, label, .role-name, .logo-text, .cat-name, .stat-label, .nav-item span, .sidebar-logout span, .footer-logo span';
  document.querySelectorAll(selector).forEach(element => {
    element.childNodes.forEach(node => {
      if (node.nodeType !== Node.TEXT_NODE || !node.textContent.trim()) return;
      if (node.__i18nOriginal === undefined) node.__i18nOriginal = node.textContent;
      const original = node.__i18nOriginal;
      const leading = original.match(/^\s*/)?.[0] || '';
      const trailing = original.match(/\s*$/)?.[0] || '';
      node.textContent = `${leading}${translateText(original.trim(), lang)}${trailing}`;
    });
  });

  document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(element => {
    if (!element.dataset.i18nPlaceholderOriginal) {
      element.dataset.i18nPlaceholderOriginal = element.placeholder;
    }
    element.placeholder = translateText(element.dataset.i18nPlaceholderOriginal, lang);
  });

  const switcher = document.getElementById('languageSelect');
  if (switcher) switcher.value = lang;
}

function createLanguageSwitcher() {
  if (document.getElementById('languageSwitcher')) return;

  const wrapper = document.createElement('div');
  wrapper.id = 'languageSwitcher';
  wrapper.className = 'language-switcher';
  wrapper.innerHTML = `
    <select id="languageSelect" aria-label="Select language">
      <option value="en">English</option>
      <option value="gu">ગુજરાતી</option>
      <option value="hi">हिन्दी</option>
    </select>
  `;
  document.body.appendChild(wrapper);

  document.getElementById('languageSelect').addEventListener('change', event => {
    localStorage.setItem(LANG_KEY, event.target.value);
    applyLanguage(event.target.value);
  });
}

